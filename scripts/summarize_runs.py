"""Collect runs/*/s*/metrics.json into markdown tables (mean ± std over seeds).

    python scripts/summarize_runs.py [--runs runs] [--out docs/results.md]

Two tables: classifiers (train.py runs) and self-supervised pretraining runs (pretrain.py, kNN monitor).
"""
from __future__ import annotations

import argparse
import json
import statistics as st
from collections import defaultdict
from pathlib import Path


def ms(vals):
    return f"{st.mean(vals):.2f} ± {st.stdev(vals):.2f}" if len(vals) > 1 else f"{vals[0]:.2f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default="runs")
    ap.add_argument("--out", default="docs/results.md")
    args = ap.parse_args()

    clf, ssl = defaultdict(list), defaultdict(list)
    for mf in sorted(Path(args.runs).glob("*/s*/metrics.json"), key=lambda p: p.stat().st_mtime):
        m = json.loads(mf.read_text())
        (ssl if "final_knn_acc" in m else clf)[m["name"]].append(m)

    hdr = ["run", "seeds", "val acc % (mean ± std)", "range", "final train/val acc %", "model", "init", "mode",
           "frozen", "labels/cls", "aug", "res", "epochs", "lr", "ls", "wd", "ema", "params M", "min/run"]
    lines = ["| " + " | ".join(hdr) + " |", "|" + "---|" * len(hdr)]
    for name, runs in clf.items():
        a = [r["best_val_acc"] * 100 for r in runs]
        tr = [r.get("final_train_acc", float("nan")) * 100 for r in runs]
        va = [r.get("final_val_acc", float("nan")) * 100 for r in runs]
        r0 = runs[0]
        init = r0["init"]
        init = "random" if init == "random" else f"{r0.get('init_method', '?')} ({Path(init).parts[1] if len(Path(init).parts) > 1 else init})"
        lines.append("| " + " | ".join([
            name, str(len(runs)), ms(a), f"{min(a):.1f}–{max(a):.1f}" if len(a) > 1 else "",
            f"{st.mean(tr):.1f} / {st.mean(va):.1f}", r0["model"], init, r0["mode"] + (f" ({r0['ssl']})" if r0["mode"] == "joint" else ""),
            "y" if r0["frozen"] else "-", str(r0.get("labels_per_class", "")), r0["aug"], str(r0["img_size"]),
            str(r0["epochs"]), f"{r0['lr']:g}", f"{r0['label_smoothing']:g}", f"{r0['weight_decay']:g}",
            "y" if r0["ema"] else "-", f"{r0['params_M']:.2f}", f"{st.mean(r['minutes'] for r in runs):.1f}"]) + " |")
    table_clf = "\n".join(lines)

    hdr2 = ["pretraining run", "seeds", "kNN val acc % at end (mean ± std)", "best kNN %", "objective", "model", "views",
            "res", "epochs", "batch", "lr", "final loss", "min/run"]
    lines = ["| " + " | ".join(hdr2) + " |", "|" + "---|" * len(hdr2)]
    for name, runs in ssl.items():
        k = [r["final_knn_acc"] * 100 for r in runs]
        b = [r["best_knn_acc"] * 100 for r in runs]
        r0 = runs[0]
        lines.append("| " + " | ".join([
            name, str(len(runs)), ms(k), ms(b), r0["ssl"], r0["model"], str(r0["views"]), str(r0["img_size"]),
            str(r0["epochs"]), str(r0["batch_size"]), f"{r0['lr']:g}", f"{st.mean(r['final_loss'] for r in runs):.3f}",
            f"{st.mean(r['minutes'] for r in runs):.1f}"]) + " |")
    table_ssl = "\n".join(lines)

    out = ("# Experiment results\n\nValidation set: 480 images (30/class) held out of the 2,400 training images; "
           "one image = 0.21 %. Generated by `scripts/summarize_runs.py`.\n\n"
           "## Classifiers (best validation epoch)\n\n" + table_clf +
           "\n\n## Self-supervised pretraining (weighted kNN, k=20, frozen features, train split -> val)\n\n" + table_ssl + "\n")
    print(out)
    if args.out:
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(out)


if __name__ == "__main__":
    main()
